_HOST_TASK_POOL = QThreadPool(maxThreadCount=6, maxPending=64, name="dialog-host")


def runtime_source_signature(root=None):
    """Cheap source identity for workers that retain imported modules in memory.

    Ignore generated bytecode and image resources so warming a worker does not
    invalidate it. Track additions/removals too, not only the top-level export
    file: shared controls and their constructor APIs can change independently.
    """
    root = os.fspath(root or Path(__file__).resolve().parents[2])
    signature = []

    def walk_error(error):
        raise error

    try:
        if not os.path.isdir(root):
            return None
        for directory, subdirs, names in os.walk(root, onerror=walk_error):
            subdirs[:] = sorted(name for name in subdirs
                                if name not in ("__pycache__", "Resources") and not name.startswith("."))
            for name in sorted(names):
                if not name.endswith(".py"):
                    continue
                path = os.path.join(directory, name)
                info = os.stat(path)
                signature.append((os.path.relpath(path, root), info.st_mtime_ns, info.st_size))
        return tuple(signature)
    except OSError:
        # An update may temporarily replace files. Never lease a cached runtime
        # if its identity cannot be checked; the normal cold path remains usable.
        return None


class QDialogHost:
    def __init__(self):
        self.ready = threading.Event()
        self.closed = False
        self.process = None
        self.connection = None
        self.messages = None
        self.listener = None
        self.hwnd = None
        self.source_signature = None
        self.reusable = False
        self.lease = None
        self.reuse_count = 0
        self.idle_ack = False
        self.last_kind = None
        self.source_epoch = None
        self._reap_started = False
        self.token = secrets.token_hex(32)
        self.log_path = floating_dialog_log_path("prewarm")

    def launch_cold(self, kind, startup_timeout=25.0):
        """Launch a normal dialog process under this reusable pool lease."""
        self.listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.listener.bind(("127.0.0.1", 0))
        self.listener.listen(1)
        self.listener.settimeout(float(startup_timeout))
        script = Path(__file__).resolve().parents[2] / "services" / "floating_dialog_process.py"
        environment = os.environ.copy()
        environment["WINUX_FLOAT_DIALOG_PORT"] = str(self.listener.getsockname()[1])
        environment["WINUX_FLOAT_DIALOG_TOKEN"] = self.token
        environment.pop("WINUX_FLOAT_DIALOG_PREWARM", None)
        self.log_path = floating_dialog_log_path(str(kind or "dialog"))
        if self.closed:
            raise RuntimeError("dialog host reservation is closed")
        self.process = launch_dialog_process(
            script, environment=environment, log_path=self.log_path,
            child_label="floating-dialog",
        )
        return self

    def prepare(self):
        try:
            self.listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            self.listener.bind(("127.0.0.1", 0))
            self.listener.listen(1)
            self.listener.settimeout(25)
            script = Path(__file__).resolve().parents[2] / "services" / "floating_dialog_process.py"
            environment = os.environ.copy()
            environment["WINUX_FLOAT_DIALOG_PORT"] = str(self.listener.getsockname()[1])
            environment["WINUX_FLOAT_DIALOG_TOKEN"] = self.token
            environment["WINUX_FLOAT_DIALOG_PREWARM"] = "1"
            Path(self.log_path).parent.mkdir(parents=True, exist_ok=True)
            if self.closed:
                return
            self.source_signature = runtime_source_signature()
            if self.source_signature is None:
                self.close()
                return
            self.process = launch_dialog_process(
                script, environment=environment, log_path=self.log_path,
                child_label="dialog-prewarm",
            )
            self.connection, _ = self.listener.accept()
            self.connection.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
            self.connection.settimeout(25)
            self.messages = read_messages(self.connection)
            hello = next(self.messages)
            if not secrets.compare_digest(str(hello.get("token", "")), self.token):
                raise ValueError("Invalid prewarm handshake")
            message = next(self.messages)
            if message.get("event") != "warm_ready":
                raise RuntimeError("Dialog worker did not finish prewarming")
            self.hwnd = int(message.get("hwnd") or 0) or None
            self.connection.settimeout(None)
            if self.closed or runtime_source_signature() != self.source_signature:
                self.close()
            else:
                self.idle_ack = True
                self.ready.set()
        except (OSError, ValueError, RuntimeError, StopIteration):
            self.close()
        finally:
            if self.listener:
                self.listener.close()

    def channel_healthy(self):
        """Return whether an already-connected reusable IPC channel is alive.

        A prewarmed process can exit in the tiny window between the pool's
        process.poll() check and the next lease. On Windows that stale socket
        surfaces as WSAECONNRESET / WinError 10054 only after the controller
        has already committed to the host. Probe with MSG_PEEK so no protocol
        bytes are consumed and reject stale workers before leasing them.
        """
        if self.closed:
            return False
        process = self.process
        if process is not None and process.poll() is not None:
            return False
        connection = self.connection
        if connection is None:
            return True
        try:
            readable, _writable, exceptional = select.select(
                [connection], [], [connection], 0)
            if exceptional:
                return False
            if not readable:
                return True
            try:
                data = connection.recv(1, socket.MSG_PEEK)
            except (BlockingIOError, InterruptedError):
                return True
            return bool(data)
        except (OSError, ValueError):
            return False

    def close(self):
        self.closed = True
        if self.connection:
            try:
                self.connection.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
            self.connection.close()
        if self.listener:
            self.listener.close()
        process = self.process
        if process is None or self._reap_started:
            return
        self._reap_started = True
        def reap():
            try:
                # Socket shutdown above is the graceful close signal.  Give the
                # helper only a short bounded drain window; retaining an Abaqus
                # child for several seconds after every dialog close causes a
                # visible pile-up under rapid open/close usage.
                process.close(timeout=0.35, force=True)
            except Exception:
                # Host shutdown is best-effort; application-wide child cleanup
                # remains the final safety net during hard exit.
                try:
                    process.terminateTree()
                except Exception:
                    pass
            finally:
                unregister_child_process(process)
        _HOST_TASK_POOL.start(reap)


class QDialogHostPool:
    def __init__(self, capacity=3, *, reusable=False, signature_cache=True, autostart=True,
                 resident_headroom=1):
        self.capacity = max(1, int(capacity))
        # ``capacity`` remains the normal total/idle target. One bounded extra
        # host may be prepared while two or more windows are leased/resident,
        # preserving a warm Qt-style top-level slot without unbounded processes.
        self.resident_headroom = max(0, int(resident_headroom))
        self.reusable = bool(reusable)
        self._lock = threading.Lock()
        self._closed = False
        self._workers = []
        self._leased = set()
        self._source_cache = None
        if signature_cache and reusable and os.name == "nt":
            self._source_cache = SourceSignatureCache(Path(__file__).resolve().parents[2],
                lambda: runtime_source_signature(), self._refresh_identity)
        if autostart:
            self._fill()

    def _identity(self):
        cache = getattr(self, "_source_cache", None)
        if cache is not None and not cache.failed:
            return cache.snapshot()
        signature = runtime_source_signature()
        epoch = cache.generation if cache is not None else None
        return SourceSnapshot(signature, epoch) if signature is not None else None

    @staticmethod
    def _matches(worker, identity):
        return bool(identity is not None and identity.signature is not None and
                    worker.source_signature == identity.signature and
                    (identity.generation is None or worker.source_epoch == identity.generation))

    def _refresh_identity(self, identity):
        retired = []
        with self._lock:
            if self._closed:
                return
            for worker in tuple(self._workers):
                if not worker.idle_ack:
                    continue
                if (self._matches(worker, identity) and not worker.closed
                        and worker.process.poll() is None and worker.channel_healthy()):
                    worker.ready.set()
                else:
                    self._workers.remove(worker)
                    retired.append(worker)
        for worker in retired:
            worker.close()
        if retired:
            self.refill()

    def _desired_idle_count(self, leased_count=None):
        leased = len(self._leased) if leased_count is None else max(0, int(leased_count))
        if leased <= 0:
            return self.capacity
        # Historically one open dialog consumed one slot (capacity=3 -> two
        # warm idle hosts). Preserve that memory profile. When another retained
        # or active window consumes a second slot, use only the bounded
        # ``resident_headroom`` to keep those two warm hosts available.
        normal_idle = max(0, self.capacity - 1)
        max_total = self.capacity + self.resident_headroom
        return min(normal_idle, max(0, max_total - leased))

    def _fill(self):
        with self._lock:
            if self._closed:
                return
            retired = [worker for worker in self._workers if worker.closed
                       or (worker.process is not None and worker.process.poll() is not None)
                       or not worker.channel_healthy()]
            self._workers = [worker for worker in self._workers if worker not in retired]
            desired_idle = self._desired_idle_count(len(self._leased))
            additions = [QDialogHost() for _ in range(max(0, desired_idle - len(self._workers)))]
            for worker in additions:
                worker.reusable = self.reusable
                if self._source_cache is not None:
                    worker.source_epoch = self._source_cache.generation
            self._workers.extend(additions)
        for worker in retired:
            worker.close()
        for worker in additions:
            _HOST_TASK_POOL.start(worker.prepare)

    def refill(self):
        _HOST_TASK_POOL.start(self._fill)

    def claim(self, *, refill=True, kind=None):
        # A user callback never waits for a worker or a preparation lock.
        if not self._lock.acquire(False):
            return None
        try:
            if self._closed:
                return None
            identity = self._identity()
            if identity is None:
                # A source change is being validated in the background. Never
                # block the UI or lease an unvalidated context.
                return None
            for candidate in self._workers:
                if candidate.idle_ack and self._matches(candidate, identity) and not candidate.closed:
                    candidate.ready.set()
            retired = [candidate for candidate in self._workers
                        if candidate.ready.is_set() and
                        not self._matches(candidate, identity)]
            self._workers = [candidate for candidate in self._workers if candidate not in retired]
            stale_channels = [worker for worker in self._workers
                if worker.ready.is_set() and not worker.closed
                and worker.process is not None and worker.process.poll() is None
                and not worker.channel_healthy()]
            if stale_channels:
                self._workers = [worker for worker in self._workers if worker not in stale_channels]
                retired.extend(worker for worker in stale_channels if worker not in retired)
            ready = [worker for worker in self._workers
                if worker.ready.is_set() and not worker.closed
                and worker.process is not None and worker.process.poll() is None
                and worker.channel_healthy()]
            # Prefer the context that last displayed this form. With two idle
            # hosts, FIFO can alternate a tiny confirmation and a large browser,
            # repeatedly resizing both swap-chains and losing the fast layout
            # match. Never wait for affinity: any ready valid host is a fallback.
            worker = next((worker for worker in ready
                           if kind is not None and getattr(worker, "last_kind", None) == kind),
                          ready[0] if ready else None)
            if worker is not None:
                self._workers.remove(worker)
                worker.ready.clear()
                worker.idle_ack = False
                worker.lease = secrets.token_hex(16)
                if self.reusable:
                    self._leased.add(worker)
            needs_refill = bool(retired) or worker is not None or any(other.closed
                or (other.process is not None and other.process.poll() is not None) for other in self._workers)
        finally:
            self._lock.release()
        for stale in retired:
            stale.close()
        if needs_refill and refill:
            self.refill()
        return worker

    def reserve_cold(self, kind=None, startup_timeout=25.0):
        """Reserve and optionally launch a reusable cold host.

        A cold launch used to be an untracked one-dialog process. Reserving a
        normal ``QDialogHost`` handle makes process ownership belong to the
        shared pool from the start. Once the first reusable form closes cleanly,
        that same process enters the idle pool.
        """
        identity = self._identity()
        if identity is None:
            return None
        with self._lock:
            if self._closed:
                return None
            worker = QDialogHost()
            worker.reusable = self.reusable
            worker.source_signature = identity.signature
            worker.source_epoch = identity.generation
            worker.lease = secrets.token_hex(16)
            worker.idle_ack = False
            self._leased.add(worker)
        if kind is not None:
            try:
                worker.launch_cold(kind, startup_timeout)
            except Exception:
                with self._lock:
                    self._leased.discard(worker)
                worker.close()
                raise
        return worker

    def release(self, worker, lease):
        """Return only an acknowledged, clean lease; never exceed capacity."""
        identity = self._identity()
        with self._lock:
            if worker not in self._leased or worker.lease != lease:
                return False
            self._leased.remove(worker)
            alive = (not self._closed and not worker.closed and
                     worker.process is not None and worker.process.poll() is None
                     and worker.channel_healthy())
            reusable = alive and self._matches(worker, identity)
            waiting = alive and identity is None and getattr(self, "_source_cache", None) is not None
            idle_limit = self._desired_idle_count(len(self._leased))
            keep = (reusable or waiting) and len(self._workers) < idle_limit
            if keep:
                worker.idle_ack = True
                worker.reuse_count += 1
                if reusable:
                    worker.ready.set()
                self._workers.append(worker)
        if not keep:
            worker.close()
            self.refill()
        return bool(reusable and keep)

    def retire(self, worker, lease=None):
        with self._lock:
            if lease is not None and worker.lease != lease:
                return
            self._leased.discard(worker)
            if worker in self._workers:
                self._workers.remove(worker)
        worker.close()
        self.refill()

    def close(self):
        with self._lock:
            self._closed = True
            workers = self._workers + list(self._leased)
            self._workers, self._leased = [], set()
        cache = getattr(self, "_source_cache", None)
        if cache is not None:
            cache.close()
        for worker in workers:
            worker.close()


def start_dialog_prewarm(view):
    if getattr(view, "_floating_focus_suppressed", False) or not view.winfo_exists():
        return
    pool = (getattr(view, "_dialog_host_pool", None)
            or getattr(view, "_dialog_prewarm_pool", None))
    if pool is None:
        # Keep only one idle Abaqus/Python dialog host.  A larger default pool
        # multiplied into several SMALncMain/SMAPython pairs even when every
        # dialog was closed.  resident_headroom=0 also prevents an extra warm
        # child from being prepared while dialogs are already leased.
        pool = QDialogHostPool(capacity=1, reusable=True, resident_headroom=0)
    view._dialog_host_pool = pool
    view._dialog_prewarm_pool = pool


class QDialogLease:
    """Exclusive lease over one dialog host process and IPC endpoint.

    The controller receives this object instead of learning how the host was
    prepared. Warm, recycled, cold-pooled and disposable fallback launches all
    present the same surface. Releasing/retiring is idempotent and lease-token
    checked by the owning pool.
    """
    def __init__(self, manager, host, *, from_prewarm=False, pooled=True):
        self.manager = manager
        self.host = host
        self.from_prewarm = bool(from_prewarm)
        self.pooled = bool(pooled)
        self.token = host.token
        self.lease = host.lease
        self.reusable = bool(host.reusable)
        self.reused = bool(host.reuse_count)
        self._finished = False
        self._state = "active"

    @property
    def process(self):
        return self.host.process

    @property
    def listener(self):
        return self.host.listener

    @property
    def connection(self):
        return self.host.connection

    @connection.setter
    def connection(self, value):
        self.host.connection = value

    @property
    def messages(self):
        return self.host.messages

    @messages.setter
    def messages(self, value):
        self.host.messages = value

    @property
    def hwnd(self):
        return self.host.hwnd

    @hwnd.setter
    def hwnd(self, value):
        self.host.hwnd = value

    @property
    def log_path(self):
        return self.host.log_path

    def open_messages(self, startup_timeout=25.0):
        """Return the authenticated event stream for this lease."""
        if self.from_prewarm and self.connection is not None and self.messages is not None:
            return self.connection, self.messages
        deadline = time.monotonic() + float(startup_timeout)
        self.listener.settimeout(min(.2, float(startup_timeout)))
        while True:
            try:
                connection, _ = self.listener.accept()
                break
            except socket.timeout:
                status = self.process.poll()
                if status is not None:
                    raise RuntimeError(
                        "Dialog host exited before connecting (exit {}). Log: {}".format(
                            status, self.log_path))
                if time.monotonic() >= deadline:
                    raise
        connection.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        connection.settimeout(float(startup_timeout))
        messages = read_messages(connection)
        hello = next(messages)
        if not secrets.compare_digest(str(hello.get("token", "")), self.token):
            connection.close()
            raise ValueError("Invalid floating-dialog handshake.")
        connection.settimeout(None)
        self.connection = connection
        self.messages = messages
        return connection, messages

    def state(self):
        return self._state

    def isActive(self):
        return not self._finished

    def release(self):
        if self._finished:
            return False
        self._finished = True
        reused = bool(self.manager.release(self))
        self._state = "released" if reused else "retired"
        return reused

    def retire(self):
        if self._finished:
            return False
        self._finished = True
        self._state = "retired"
        self.manager.retire(self)
        return True

    def close_listener(self):
        listener = self.listener
        if listener is not None:
            try:
                listener.close()
            except OSError:
                pass

    def close_channel(self, *, connection=True, listener=True):
        if connection and self.connection is not None:
            try:
                self.connection.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
            try:
                self.connection.close()
            except OSError:
                pass
        if listener:
            self.close_listener()

    def cancel(self):
        """Cancel this lease and retire its host instead of recycling it."""
        if self._finished:
            return False
        self._finished = True
        self._state = "cancelled"
        self.manager.retire(self)
        return True

    def dispose(self, *, recycle=False):
        return self.release() if recycle else self.retire()


class QDialogHostManager:
    """Per-view service owning all floating dialog host acquisition/disposal."""
    def __init__(self, view, pool=None):
        self.view = view
        self._pool = pool
        self._closed = False
        self._lease_lock = threading.RLock()
        self._leases = set()
        # Retained dialogs are a cache, not an unbounded collection of worker
        # processes. Keep the most recently used hidden tools alive and recycle
        # older hidden hosts back into the normal warm pool.
        self._resident_hidden = OrderedDict()
        self._resident_limit = max(0, int(getattr(view, "_dialog_resident_limit", 6)))

    @property
    def pool(self):
        # Preserve compatibility with startup code/tests that replace the old
        # ``_dialog_prewarm_pool`` attribute after the manager was created.
        current = getattr(self.view, "_dialog_host_pool", None)
        legacy = getattr(self.view, "_dialog_prewarm_pool", None)
        if legacy is not None and legacy is not self._pool:
            current = legacy
        if current is not None and current is not self._pool:
            self._pool = current
        if self._pool is None and not self._closed:
            self._pool = QDialogHostPool(reusable=True, autostart=False)
        if self._pool is not None:
            self.view._dialog_host_pool = self._pool
            self.view._dialog_prewarm_pool = self._pool
        return self._pool

    def _track(self, lease):
        with self._lease_lock:
            if self._closed:
                lease.host.close()
                lease._finished = True
                lease._state = "retired"
                raise RuntimeError("dialog host manager is closed")
            self._leases.add(lease)
        return lease

    def _untrack(self, lease):
        with self._lease_lock:
            self._leases.discard(lease)

    def retained_visible(self, controller):
        """Mark a retained top-level MRU/visible so it cannot be evicted hidden."""
        with self._lease_lock:
            self._resident_hidden.pop(controller, None)

    def retained_hidden(self, controller):
        """Cache a hidden retained top-level and evict old hidden entries LRU.

        Eviction is deferred to the view queue. A dialog reopened before that
        turn increments its resident generation and therefore survives.
        """
        victims = []
        with self._lease_lock:
            if self._closed or getattr(controller, "_closed", False):
                return
            self._resident_hidden.pop(controller, None)
            self._resident_hidden[controller] = getattr(controller, "_resident_generation", 0)
            while len(self._resident_hidden) > self._resident_limit:
                victim, generation = self._resident_hidden.popitem(last=False)
                victims.append((victim, generation))
        for victim, generation in victims:
            after = getattr(self.view, "after", None)
            if callable(after):
                after(0, victim._evict_retained, generation)
            else:
                victim._evict_retained(generation)

    def forget_resident(self, controller):
        with self._lease_lock:
            self._resident_hidden.pop(controller, None)

    def acquire(self, kind, startup_timeout=25.0, *, fresh=False):
        if self._closed:
            raise RuntimeError("dialog host manager is closed")
        pool = self.pool
        host = (pool.claim(refill=False, kind=kind)
                if pool is not None and not fresh else None)
        from_prewarm = host is not None
        if host is None and pool is not None and getattr(pool, "reusable", False):
            host = pool.reserve_cold(kind, startup_timeout)
        if host is not None:
            host.last_kind = kind
            return self._track(QDialogLease(
                self, host, from_prewarm=from_prewarm, pooled=True))

        # Conservative disposable fallback used while source identity is being
        # validated or when a legacy non-reusable pool has no ready host.
        host = QDialogHost()
        host.reusable = False
        host.lease = None
        try:
            host.launch_cold(kind, startup_timeout)
        except Exception:
            host.close()
            raise
        return self._track(QDialogLease(
            self, host, from_prewarm=False, pooled=False))

    def release(self, lease):
        self._untrack(lease)
        pool = self.pool
        if not lease.pooled or pool is None:
            lease.host.close()
            return False
        return pool.release(lease.host, lease.lease)

    def retire(self, lease):
        self._untrack(lease)
        pool = self.pool
        if lease.pooled and pool is not None:
            pool.retire(lease.host, lease.lease)
        else:
            lease.host.close()

    def refill(self):
        pool = self.pool
        if pool is not None:
            pool.refill()

    def close(self):
        if self._closed:
            return
        self._closed = True
        with self._lease_lock:
            leases = tuple(self._leases)
            self._leases.clear()
            self._resident_hidden.clear()
        pool = (self._pool or getattr(self.view, "_dialog_host_pool", None)
                or getattr(self.view, "_dialog_prewarm_pool", None))
        if pool is not None:
            pool.close()
        # Pool close owns pooled hosts. Disposable fallback leases are outside
        # that registry and must still be retired here. Mark every outstanding
        # lease terminal so later controller cleanup stays idempotent.
        for lease in leases:
            if not lease.pooled:
                lease.host.close()
            lease._finished = True
            lease._state = "retired"


def dialog_host_manager(view):
    manager = getattr(view, "_dialog_host_manager", None)
    if manager is None or getattr(manager, "_closed", False):
        manager = QDialogHostManager(
            view, getattr(view, "_dialog_host_pool", None)
            or getattr(view, "_dialog_prewarm_pool", None))
        view._dialog_host_manager = manager
        # Materialize/synchronize the pool aliases once at service creation.
        manager.pool
    return manager


